List<UiPattern> filterPatterns({
  String query = '',
  UiCategory? category,
  PlatformScope? platform,
  bool favoritesOnly = false,
  Set<String> favoriteIds = const <String>{},
}) {
  final needle = normalizeSearch(query);

  return uiPatterns
      .where((pattern) {
        final categoryMatches =
            category == null || pattern.category == category;
        final platformMatches =
            platform == null ||
            pattern.platform == PlatformScope.shared ||
            pattern.platform == platform;
        final favoriteMatches =
            !favoritesOnly || favoriteIds.contains(pattern.id);
        final haystack = normalizeSearch(
          <String>[
            pattern.name,
            pattern.english,
            pattern.summary,
            pattern.useWhen,
            pattern.avoid,
            pattern.compare,
            pattern.a11y,
            ...pattern.examples,
          ].join(' '),
        );
        final queryMatches = needle.isEmpty || haystack.contains(needle);

        return categoryMatches &&
            platformMatches &&
            favoriteMatches &&
            queryMatches;
      })
      .toList(growable: false);
}
